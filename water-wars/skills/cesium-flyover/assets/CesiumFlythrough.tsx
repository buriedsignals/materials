import React, { useEffect, useRef, useState } from "react";
import {
  AbsoluteFill,
  continueRender,
  delayRender,
  useCurrentFrame,
  useVideoConfig,
} from "remotion";
import cesiumPath from "../geo/cesium-path.json";

// Cesium spike (TODO #4a): MapTiler quantized-mesh terrain + MapTiler satellite imagery, driven along
// Pilot B's exact camera path, rendered through Remotion's headless Chrome (the proven WebGL pipeline)
// so it's an apples-to-apples comparison against the MapLibre raster-DEM drape (PilotB-GreatBend).
// Cesium loads from CDN at runtime (avoids bundling Cesium's webpack static assets).

const KEY = process.env.REMOTION_MAPTILER_KEY as string;
const CESIUM_VER = "1.124";
const CDN = `https://cesium.com/downloads/cesiumjs/releases/${CESIUM_VER}/Build/Cesium/`;

// Camera params + a gently-curved path (../geo/cesium-path.json, generated by prep-cesium-path.mjs) so
// the camera swerves slightly through the gorge — "helicopter flying through" — with a subtle bank.
// ADAPT for a new location: ALT_START/END to your terrain's elevation; speed = TRAVEL_KM / durationSeconds.
const ALT_START = 4600; // m ASL — fly THROUGH the corridor (Tibet gorge floor ~2900 m, peaks ~7000 m)
const ALT_END = 4300;
const LOOK_AHEAD_KM = 1.5;
const TRAVEL_KM = 13; // travel distance; the proven render pairs this with a 24 s / 720-frame Composition (≈0.54 km/s)
const PITCH_FROM_NADIR = 76; // 90 = horizon → Cesium pitch = -(90-76) = -14°
const EXAGG = 1.1;
const MAX_BANK = 0.13; // rad (~7.5°) — gentle helicopter roll into the swerves
const BANK_GAIN = 0.6;

const R = 6371;
const havKm = (a: number[], b: number[]) => {
  const r = Math.PI / 180, dLat = (b[1] - a[1]) * r, dLng = (b[0] - a[0]) * r;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a[1] * r) * Math.cos(b[1] * r) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};
// Arc-length walk along the curved path.
const PATH = cesiumPath as [number, number][];
const CUM: number[] = [0];
for (let i = 1; i < PATH.length; i++) CUM.push(CUM[i - 1] + havKm(PATH[i - 1], PATH[i]));
const PATHKM = CUM[CUM.length - 1];
const alongPath = (km: number): [number, number] => {
  const d = Math.max(0, Math.min(PATHKM, km));
  let i = 1;
  while (i < CUM.length && CUM[i] < d) i++;
  if (i >= CUM.length) return PATH[PATH.length - 1];
  const t = (d - CUM[i - 1]) / ((CUM[i] - CUM[i - 1]) || 1);
  return [PATH[i - 1][0] + (PATH[i][0] - PATH[i - 1][0]) * t, PATH[i - 1][1] + (PATH[i][1] - PATH[i - 1][1]) * t];
};
const bearing = (a: number[], b: number[]) => {
  const r = Math.PI / 180;
  const y = Math.sin((b[0] - a[0]) * r) * Math.cos(b[1] * r);
  const x = Math.cos(a[1] * r) * Math.sin(b[1] * r) - Math.sin(a[1] * r) * Math.cos(b[1] * r) * Math.cos((b[0] - a[0]) * r);
  return Math.atan2(y, x);
};
const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
const clamp = (v: number, lo: number, hi: number) => Math.max(lo, Math.min(hi, v));

const loadCesium = () =>
  new Promise<any>((resolve) => {
    if ((window as any).Cesium) return resolve((window as any).Cesium);
    (window as any).CESIUM_BASE_URL = CDN;
    const css = document.createElement("link");
    css.rel = "stylesheet";
    css.href = `${CDN}Widgets/widgets.css`;
    document.head.appendChild(css);
    const s = document.createElement("script");
    s.src = `${CDN}Cesium.js`;
    s.onload = () => resolve((window as any).Cesium);
    document.head.appendChild(s);
  });

export const CesiumFlythrough: React.FC = () => {
  const ref = useRef<HTMLDivElement>(null);
  const started = useRef(false);
  const viewerRef = useRef<any>(null);
  const frame = useCurrentFrame();
  const { durationInFrames, width, height } = useVideoConfig();
  const [ready, setReady] = useState(false);
  const [handle] = useState(() => delayRender("cesium init", { timeout: 120000 }));

  const setCamera = (C: any, viewer: any, prog: number) => {
    const dCam = Math.min(TRAVEL_KM, PATHKM - LOOK_AHEAD_KM * 2) * prog;
    const cam = alongPath(dCam);
    const aim = alongPath(dCam + LOOK_AHEAD_KM);
    const aim2 = alongPath(dCam + LOOK_AHEAD_KM * 2);
    const camAlt = lerp(ALT_START, ALT_END, prog);
    const heading = bearing(cam, aim);
    let dH = bearing(aim, aim2) - heading; // turn rate ahead → bank into it
    while (dH > Math.PI) dH -= 2 * Math.PI;
    while (dH < -Math.PI) dH += 2 * Math.PI;
    viewer.camera.setView({
      destination: C.Cartesian3.fromDegrees(cam[0], cam[1], camAlt),
      orientation: {
        heading,
        pitch: C.Math.toRadians(-(90 - PITCH_FROM_NADIR)),
        roll: clamp(dH * BANK_GAIN, -MAX_BANK, MAX_BANK),
      },
    });
  };

  const settle = (viewer: any) =>
    new Promise<void>((resolve) => {
      let stable = 0, ticks = 0;
      const tick = () => {
        viewer.render(); // full frame — advances tile streaming
        ticks++;
        if (viewer.scene.globe.tilesLoaded) stable++;
        else stable = 0;
        if (stable > 8 || ticks > 600) {
          viewer.render();
          resolve();
        } else setTimeout(tick, 8);
      };
      tick();
    });

  useEffect(() => {
    if (started.current) return;
    started.current = true;
    (async () => {
      const C = await loadCesium();
      const viewer = new C.Viewer(ref.current, {
        baseLayer: false,
        baseLayerPicker: false, geocoder: false, homeButton: false, sceneModePicker: false,
        navigationHelpButton: false, animation: false, timeline: false, fullscreenButton: false,
        infoBox: false, selectionIndicator: false,
        contextOptions: { webgl: { preserveDrawingBuffer: true } },
      });
      viewer.imageryLayers.addImageryProvider(
        new C.UrlTemplateImageryProvider({
          url: `https://api.maptiler.com/tiles/satellite-v2/{z}/{x}/{y}.jpg?key=${KEY}`,
          maximumLevel: 20, credit: "MapTiler",
        }),
      );
      viewer.useDefaultRenderLoop = false;
      viewer.scene.skyAtmosphere.show = true;
      viewer.scene.fog.enabled = true;
      viewer.scene.globe.enableLighting = false;
      viewer.scene.verticalExaggeration = EXAGG;
      viewer.cesiumWidget.creditContainer.style.display = "none";
      viewer.terrainProvider = await C.CesiumTerrainProvider.fromUrl(
        `https://api.maptiler.com/tiles/terrain-quantized-mesh-v2/?key=${KEY}`,
        { requestVertexNormals: true },
      );
      (window as any).__C = C;
      viewerRef.current = viewer;
      setCamera(C, viewer, 0);
      await settle(viewer);
      setReady(true);
      continueRender(handle);
    })();
  }, [handle]);

  useEffect(() => {
    if (!ready) return;
    const h = delayRender(`cesium frame ${frame}`, { timeout: 60000 });
    const C = (window as any).__C;
    const viewer = viewerRef.current;
    const prog = durationInFrames <= 1 ? 0 : frame / (durationInFrames - 1);
    setCamera(C, viewer, prog);
    settle(viewer).then(() => continueRender(h));
  }, [ready, frame, durationInFrames]);

  return (
    <AbsoluteFill style={{ backgroundColor: "#000" }}>
      <div ref={ref} style={{ width, height, position: "absolute" }} />
    </AbsoluteFill>
  );
};
